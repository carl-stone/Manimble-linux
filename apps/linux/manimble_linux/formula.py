"""LaTeX sheet using the engine's real compiler and generation-checked previews."""
from __future__ import annotations
from PySide6.QtCore import Qt, QTimer
from PySide6.QtGui import QFontDatabase, QKeySequence, QPixmap, QShortcut
from PySide6.QtWidgets import QCheckBox, QDialog, QDialogButtonBox, QLabel, QPlainTextEdit, QVBoxLayout
from .tasks import spawn


class LatexSheet(QDialog):
    def __init__(self, initial, shared, render, apply, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Edit formula"); self.resize(640, 470)
        self.render_fn, self.apply_fn = render, apply
        self.generation = 0
        self.text = QPlainTextEdit(initial)
        self.text.setFont(QFontDatabase.systemFont(QFontDatabase.SystemFont.FixedFont))
        self.preview = QLabel(); self.preview.setMinimumHeight(150); self.preview.setAlignment(Qt.AlignmentFlag.AlignCenter); self.preview.setStyleSheet("background:black")
        self.err_label = QLabel(); self.err_label.setWordWrap(True); self.err_label.setStyleSheet("color:#FC6255")
        self.shared_box = None
        layout = QVBoxLayout(self)
        layout.addWidget(QLabel("LaTeX · Ctrl+Return applies")); layout.addWidget(self.text); layout.addWidget(self.preview, 1); layout.addWidget(self.err_label)
        if shared:
            self.shared_box = QCheckBox(f"Change everywhere ({shared.get('name')} in {shared.get('rel')}, used {shared.get('uses')}×). Untick for this slide only.")
            self.shared_box.setChecked(True); layout.addWidget(self.shared_box)
        buttons = QDialogButtonBox(QDialogButtonBox.StandardButton.Apply | QDialogButtonBox.StandardButton.Cancel)
        buttons.button(QDialogButtonBox.StandardButton.Apply).clicked.connect(self.apply_pressed); buttons.rejected.connect(self.reject); layout.addWidget(buttons)
        QShortcut(QKeySequence("Ctrl+Return"), self, activated=self.apply_pressed)
        self.timer = QTimer(self); self.timer.setSingleShot(True); self.timer.setInterval(300); self.timer.timeout.connect(self.load_preview)
        self.text.textChanged.connect(self.refresh)
        self.finished.connect(lambda _: self.cancel_preview())
        self.refresh()

    def cancel_preview(self): self.generation += 1; self.timer.stop()
    def refresh(self): self.generation += 1; self.timer.start()
    def load_preview(self):
        generation, text = self.generation, self.text.toPlainText()
        def work():
            try:
                result = yield self.render_fn(text)
                path, error = result.get("path"), result.get("error")
            except Exception as exc:
                path, error = None, str(exc)
            if generation != self.generation: return
            if path:
                pixmap = QPixmap(path)
                if pixmap.isNull(): self.err_label.setText(f"Cannot read preview: {path}")
                else:
                    self.preview.setPixmap(pixmap.scaled(self.preview.size(), Qt.AspectRatioMode.KeepAspectRatio, Qt.TransformationMode.SmoothTransformation)); self.err_label.clear()
            else:
                self.err_label.setText("\n".join(str(error or "LaTeX error").splitlines()[-4:]))
        spawn(work())
    def apply_pressed(self):
        text = self.text.toPlainText(); shared = self.shared_box is None or self.shared_box.isChecked()
        self.accept(); self.apply_fn(text, shared)


class FormulaMixin:
    def _formula_render(self, tex):
        return self.call("sprite", {"kind": "tex", "value": tex, "font_size": 40.0, "color": "#FFFFFF"})
    def open_latex(self, oid):
        obj = (self.scene or {}).get("objects", {}).get(str(oid), {})
        if obj.get("kind") != "tex": return
        if not obj.get("textOk"):
            self.toast("This formula is generated by code: " + obj.get("textNote", "computed"), error=True); return
        context = self.edit_context
        sheet = LatexSheet(obj.get("value", ""), obj.get("shared"), self._formula_render,
                           lambda tex, shared: self.commit_text(oid, tex, shared=shared, slide=context.scene, seen=context.seen), self.window)
        self.latex_sheet = sheet
        sheet.open()
    def edit_latex_pressed(self):
        if self.selection is not None: return self.open_latex(self.selection)
    def insert_formula_pressed(self):
        if not self.scene_name: return
        context = self.edit_context
        def apply(tex, _):
            if self.scene_name != context.scene or self.stop_index != context.stop:
                self.toast("The slide changed; choose Insert Formula again", error=True); return
            self.insert("formula", {"tex": tex})
        self.latex_sheet = LatexSheet("x^2 + y^2 = z^2", None, self._formula_render, apply, self.window)
        self.latex_sheet.open()
